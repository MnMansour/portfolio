import type { ReactNode, SVGProps } from 'react'
import { useReveal } from '../hooks/useReveal'

export function Reveal({
  children,
  className = '',
  delay = 0,
}: {
  children: ReactNode
  className?: string
  delay?: number
}) {
  const ref = useReveal<HTMLDivElement>()
  return (
    <div ref={ref} className={`reveal ${className}`} style={{ transitionDelay: `${delay}ms` }}>
      {children}
    </div>
  )
}

export function Section({
  id,
  eyebrow,
  title,
  description,
  children,
}: {
  id: string
  eyebrow: string
  title: ReactNode
  description?: string
  children: ReactNode
}) {
  return (
    <section id={id} className="container-page py-24 sm:py-32">
      <Reveal className="mb-14 max-w-2xl">
        <p className="mb-3 font-mono text-xs uppercase tracking-[0.25em] text-accent-cyan">
          <span className="text-slate-500">//</span> {eyebrow}
        </p>
        <h2 className="text-3xl font-bold tracking-tight sm:text-4xl">{title}</h2>
        {description && <p className="mt-4 text-base leading-relaxed text-slate-400">{description}</p>}
      </Reveal>
      {children}
    </section>
  )
}

